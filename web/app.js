  async function startTraining() {
    const inp = App.inputs[7];
    const payload = { learning_rate: Number($('#l7-lr').value), steps: Number($('#l7-steps').value) || inp.steps,
      batch_size: Number($('#l7-bs').value), seed: Math.max(0, parseInt($('#l7-seed').value, 10) || 0) };
    Object.assign(inp, payload);
    $('#l7-start').disabled = true;
    try {
      const r = await api('/api/train/start', { method: 'POST', json: payload });
      App.state.training = r.training;
      App.progress = { running: true, run_done: 0, run_total: payload.steps, step: r.training.step, run_target: r.training.run_target };
      openStream();
      renderTraining();
      updateTrainBadge();
    } catch (err) {
      toast(err.message, 'error');
      $('#l7-start').disabled = false;
    }
  }

  async function stopTraining() {
    try {
      await api('/api/train/stop', { method: 'POST' });
      toast('Stop request sent: training will end at the next step.', 'info');
    } catch (err) {
      toast(err.message, 'error');
    }
  }

  async function resetModel() {
    const seed = Math.max(0, parseInt($('#l7-seed').value, 10) || 0);
    if (!window.confirm('Reset the model with seed ' + seed + '?\n\nThe trained weights and gallery will be cleared; the model returns to step 0.')) return;
    try {
      const r = await api('/api/model/reset', { method: 'POST', json: { seed: seed } });
      App.progress = null;
      applyState(r.state);
      toast(r.message, 'success');
      renderVizPane(7);
    } catch (err) {
      toast(err.message, 'error');
    }
  }

  // ------------------------------------------------------------------ Server-Sent Events
  function upsertByStep(list, item) {
    const i = list.findIndex(function (x) { return x.step === item.step; });
    if (i >= 0) list[i] = item;
    else { list.push(item); list.sort(function (a, b) { return a.step - b.step; }); }
  }

  function closeStream() {
    if (App.es) { App.es.close(); App.es = null; }
  }

  async function finishTraining() {
    closeStream();
    App.progress = null;
    try { await refreshState(); } catch (err) { toast(err.message, 'error'); }
    if (App.panel && App.panel.alive && App.panel.lab === 7) renderVizPane(7);
    updateTrainBadge();
  }

  function openStream() {
    if (App.es) return;
    const es = new EventSource('/api/train/stream');
    App.es = es;
    es.addEventListener('progress', function (e) {
      const d = JSON.parse(e.data);
      if (d.snapshot) {
        if (!d.running) { finishTraining(); return; }
        App.progress = Object.assign({}, App.progress || {}, { running: true, step: d.step, run_target: d.run_target,
          run_total: d.config ? d.config.steps : null, run_done: d.step - d.run_start });
      } else {
        App.progress = d;
      }
      updateTrainBadge();
      renderTraining();
    });
    es.addEventListener('eval', function (e) {
      upsertByStep(App.state.history.evals, JSON.parse(e.data));
      if (lab7Visible()) {
        renderLossChart();
        loadMatrix(App.panel, 7, App.inputs[7].mode, $('#l7-matrix'));
      }
    });
    es.addEventListener('sample', function (e) {
      upsertByStep(App.state.history.samples, JSON.parse(e.data));
      if (lab7Visible()) renderGallery();
    });
    es.addEventListener('done', function (e) {
      const d = JSON.parse(e.data);
      toast(d.message + (d.saved ? ' Model saved to .workshop/model.pt.' : ''), 'success', 8000);
      finishTraining();
    });
    es.addEventListener('error', function (e) {
      if (!e.data) return; // connection hiccup: EventSource reconnects by itself
      const d = JSON.parse(e.data);
      toast('Training stopped with an error: ' + d.text, 'error', 15000);
      finishTraining();
    });
  }

