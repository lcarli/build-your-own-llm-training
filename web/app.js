  // ------------------------------------------------------------------ shared rendering helpers
  function codeExcerpt(e) {
    if (!e || !e.line) return '';
    const loc = '<div class="err-loc">' + esc(e.path || '') + ', line ' + e.line + (e.col ? ', column ' + e.col : '') + '</div>';
    if (e.code === null || e.code === undefined) return loc;
    const raw = String(e.code).replace(/\n$/, '');
    let text = '';
    let col = null;
    for (let i = 0; i < raw.length; i++) {
      if (e.col && i === e.col - 1) col = text.length;
      text += raw[i] === '\t' ? '    ' : raw[i];
    }
    if (e.col && col === null) col = text.length;
    const gutter = String(e.line) + ' | ';
    let body;
    if (col !== null) {
      const at = text.slice(col, col + 1);
      const shown = at && /[\s\u00a0\u200b-\u200f\u2028\u2029\u2060\ufeff]/.test(at) ? '·' : at;
      body = esc(gutter + text.slice(0, col)) + (at ? '<mark>' + esc(shown) + '</mark>' : '') + esc(text.slice(col + 1)) +
        '\n' + ' '.repeat(gutter.length + col) + '^';
    } else {
      body = esc(gutter + text);
    }
    return loc + '<pre class="err-code">' + body + '</pre>';
  }

