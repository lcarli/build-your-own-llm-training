  function renderTraining() {
    if (!lab7Visible()) return;
    const d = App.train;
    const t = App.state.training;
    const p = App.progress;
    const running = !!((p && p.running) || t.running);
    $('#l7-start').disabled = running;
    $('#l7-stop').disabled = !running;
    $('#l7-reset').disabled = running;
    ['l7-lr', 'l7-steps', 'l7-bs', 'l7-seed'].forEach(function (id) { $('#' + id).disabled = running; });
    const step = p ? p.step : App.state.model.step;
    let prog = '';
    if (running && p && p.run_total) {
      const pct = Math.min(100, p.run_done / p.run_total * 100);
      prog = '<div class="progress"><div class="progress-bar" style="width:' + pct.toFixed(1) + '%"></div></div>' +
        '<div class="progress-text">step ' + fmtInt(p.step) + ' · ' + fmtInt(p.run_done) + ' of ' + fmtInt(p.run_total) + ' in this run' +
        (p.steps_per_sec ? ' · ' + fmtInt(p.steps_per_sec) + ' steps/s' : '') + (p.loss !== null && p.loss !== undefined ? ' · last batch loss ' + fmt(p.loss, 3) : '') + '</div>';
    } else if (running) {
      prog = '<div class="progress-text">Preparing training…</div>';
    } else {
      prog = '<div class="progress-text">Model at step <strong>' + fmtInt(step) + '</strong>' + (step === 0 ? ' (not yet trained)' : '') + ' · model seed ' + App.state.model.seed +
        ' · ' + fmtInt(App.state.model.params || 0) + ' parameters.' + (step === 0 ? ' Choose the values and click Start.' : ' Start continues training this model; Reset model returns to the beginning.') + '</div>';
    }
    if (t.error && !running) prog += errorBox({ message: 'Training stopped with an error: ' + t.error.type + ': ' + t.error.message, data: { detail: t.error } });
    $('#l7-progress').innerHTML = prog;
    renderLossChart();
    renderGallery();
  }

  function renderLossChart() {
    const el = $('#l7-chart');
    if (!el) return;
    const d = App.train;
    const evals = App.state.history.evals;
    const p = App.progress;
    if (!evals.length) {
      el.innerHTML = '<div class="empty">The curves appear when training starts: loss is measured at step 0 and every ' +
        App.state.constants.eval_interval + ' steps.</div>';
      return;
    }
    const lastStep = evals[evals.length - 1].step;
    const previous = App.state.previous_curves || [];
    const prevMax = Math.max.apply(null, previous.map(function (c) { return c.points[c.points.length - 1][0]; }).concat([0]));
    const target = Math.max(lastStep, prevMax, (p && p.run_target) || 0, App.state.training.run_target || 0);
    const series = [
      { name: 'training', color: '#0f766e', points: evals.map(function (e) { return [e.step, e.train]; }) },
      { name: 'validation', color: '#e8590c', points: evals.map(function (e) { return [e.step, e.val]; }) },
    ].concat(previous.map(function (c, i) {
      return { name: 'previous training (' + c.label + ')', color: PREVIOUS_COLORS[i % PREVIOUS_COLORS.length], faint: true,
        points: c.points.map(function (q) { return [q[0], q[1]]; }) };
    }));
    const svg = C.lineChart(series, { width: widthOf(el, 640), height: 310, xLabel: 'training step', yLabel: 'loss', xMax: Math.max(target, 1),
      refLine: { y: d.floor, label: 'bigram limit (training)' }, decimals: 2, label: 'loss curves' });
    const last = evals[evals.length - 1];
    el.innerHTML = svg + '<div class="note">Latest evaluation (step ' + fmtInt(last.step) + '): training ' + fmt(last.train, 3) + ' · validation ' + fmt(last.val, 3) +
      ' · bigram limit ' + fmt(d.floor, 3) + ' · ln V = ' + fmt(d.ln_vocab, 3) + ' (uniform model)' +
      (previous.length ? '. Thin lines represent previous models (before Reset model), for comparing learning rates.' : '') + '</div>' +
      prov('mean of ' + App.state.constants.eval_batches + ' batches per evaluation (block size ' + App.state.constants.block_size + ') using your get_batch + next_token_loss, without gradients · ' +
        'limit = H(next | current) counted from training text pairs');
  }

